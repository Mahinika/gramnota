class GcodeFilament {
  const GcodeFilament({
    required this.grams,
    this.material = '',
    this.colorHex = '',
  });

  final double grams;
  final String material;
  final String colorHex;
}

/// One sliced plate or a single `.gcode` file.
class GcodePlate {
  const GcodePlate({
    required this.name,
    required this.slicer,
    required this.printTimeSeconds,
    required this.filaments,
    this.notes = const [],
  });

  final String name;
  final String slicer;
  final int? printTimeSeconds;
  final List<GcodeFilament> filaments;
  final List<String> notes;

  bool get hasData => printTimeSeconds != null || filaments.isNotEmpty;
}

class GcodeImport {
  const GcodeImport({
    required this.title,
    required this.plates,
    this.note = '',
  });

  final String title;
  final List<GcodePlate> plates;
  final String note;

  bool get hasData => plates.any((plate) => plate.hasData);
}

/// How many bytes of a G-code file are inspected.
///
/// Slicer summaries sit in the header (Prusa, Orca, Bambu, Creality Print) or
/// the footer (Cura). The toolpath in between is skipped.
const gcodeHeadBytes = 1024 * 1024;
const gcodeTailBytes = 256 * 1024;

const _defaultDiameterMm = 1.75;
const _defaultDensity = 1.24;

/// Reads slicer comments. [text] should already be only the header and footer.
GcodePlate parseGcodeText(String text, {String name = ''}) {
  final parser = _GcodeCommentParser();
  for (final raw in text.split('\n')) {
    final line = raw.trim();
    if (line.isEmpty || !line.startsWith(';')) {
      continue;
    }
    parser.addComment(line.substring(1).trim());
  }
  return parser.finish(name: name);
}

String gcodePlateNote(
  GcodePlate plate, {
  required AppLocalizations l10n,
  int plateCount = 1,
}) {
  if (!plate.hasData) {
    return l10n.gcodeNoData;
  }
  final parts = <String>[
    plate.slicer.isEmpty
        ? l10n.gcodeFilledFromFile
        : l10n.gcodeFilledFromSlicer(plate.slicer),
    l10n.gcodeSalePriceUsesSpools,
    if (plate.filaments.length > 1)
      l10n.gcodeFilamentsListed(plate.filaments.length),
    ...plate.notes,
    if (plateCount > 1) l10n.gcodeFilePlateCount(plateCount),
  ];
  return parts.join(' ');
}

class _GcodeCommentParser {
  String _slicer = '';
  int? _normalSeconds;
  int? _totalSeconds;
  int? _modelSeconds;
  int? _genericSeconds;
  int? _curaSeconds;
  List<double>? _grams;
  List<double>? _totalGrams;
  List<double>? _lengthMm;
  List<double>? _lengthM;
  List<double>? _volumeCm3;
  List<double>? _diameters;
  List<double>? _densities;
  final List<String> _materials = [];
  final List<String> _colors = [];

  void addComment(String body) {
    if (body.isEmpty) {
      return;
    }
    _readSlicer(body);
    _consumePair(body);
  }

  GcodePlate finish({required String name}) {
    final built = _filaments();
    return GcodePlate(
      name: name,
      slicer: _slicer,
      printTimeSeconds: _bestTime(),
      filaments: built.filaments,
      notes: built.notes,
    );
  }

  void _readSlicer(String body) {
    final lower = body.toLowerCase();
    if (lower.contains('generated by') || lower.contains('generated with')) {
      _slicer = _slicerLabel(body);
      return;
    }
    if (_slicer.isEmpty &&
        (lower.contains('bambustudio') || lower.contains('bambu studio'))) {
      _slicer = 'Bambu Studio';
    }
  }

  void _consumePair(String text) {
    final match = RegExp(r'^([^:=]+?)\s*[:=]\s*(.*)$').firstMatch(text.trim());
    if (match == null) {
      return;
    }
    final key = match.group(1)!.trim();
    final rest = match.group(2)!;
    final pieces = rest.split(RegExp(r';\s*(?=[^;:=]+[:=])'));
    _record(key, pieces.first.trim());
    for (final extra in pieces.skip(1)) {
      _consumePair(extra.trim());
    }
  }

  void _record(String key, String value) {
    final loose = key
        .trim()
        .toLowerCase()
        .replaceAll(RegExp(r'\s+'), ' ')
        .replaceAll('_', ' ');
    if (loose.contains('silent')) {
      return;
    }
    if (loose.contains('normal mode')) {
      _normalSeconds = _parseDuration(value) ?? _normalSeconds;
      return;
    }
    if (loose.contains('total estimated time')) {
      _totalSeconds = _parseDuration(value) ?? _totalSeconds;
      return;
    }
    if (loose.contains('model printing time')) {
      _modelSeconds = _parseDuration(value) ?? _modelSeconds;
      return;
    }
    if (loose == 'time') {
      _curaSeconds = _parseDuration(value) ?? _curaSeconds;
      return;
    }
    if (loose.contains('print time') || loose.contains('printing time')) {
      _genericSeconds = _parseDuration(value) ?? _genericSeconds;
      return;
    }
    if (loose == 'filament used [g]' ||
        loose == 'filament weight' ||
        loose == 'material weight' ||
        loose == 'filament weight [g]') {
      _grams = _parseNumberList(value);
      return;
    }
    if (loose == 'total filament used [g]' ||
        loose == 'total filament weight') {
      _totalGrams = _parseNumberList(value);
      return;
    }
    if (loose == 'filament used [mm]') {
      _lengthMm = _parseNumberList(value);
      return;
    }
    if (loose == 'filament used [cm3]' || loose == 'filament used [cm³]') {
      _volumeCm3 = _parseNumberList(value);
      return;
    }
    if (loose == 'filament used') {
      final lower = value.toLowerCase();
      if (lower.contains('mm')) {
        _lengthMm = _parseNumberList(value);
      } else if (RegExp(r'\d\s*m\b').hasMatch(lower)) {
        _lengthM = _parseNumberList(value);
      } else if (lower.contains('g')) {
        _grams = _parseNumberList(value);
      }
      return;
    }
    if (loose == 'filament type' || loose == 'filament types') {
      _assignLabels(_materials, _splitLabels(value));
      return;
    }
    if (loose == 'filament colour' ||
        loose == 'filament color' ||
        loose == 'filament colors' ||
        loose == 'filament colours') {
      _assignLabels(_colors, [
        for (final color in _splitLabels(value)) _normalizeColor(color),
      ]);
      return;
    }
    if (loose == 'filament diameter' || loose == 'filament diameter [mm]') {
      _diameters = _parseNumberList(value);
      return;
    }
    if (loose == 'filament density') {
      _densities = _parseNumberList(value);
      return;
    }
    final materialKey = RegExp(r'^material(\d*)$').firstMatch(loose);
    if (materialKey != null) {
      final suffix = materialKey.group(1)!;
      final index = suffix.isEmpty ? 0 : int.parse(suffix) - 1;
      if (index >= 0) {
        _setIndex(_materials, index, _cleanLabel(value));
      }
    }
  }

  int? _bestTime() {
    return _normalSeconds ??
        _totalSeconds ??
        _modelSeconds ??
        _genericSeconds ??
        _curaSeconds;
  }

  ({List<GcodeFilament> filaments, List<String> notes}) _filaments() {
    var estimated = false;
    var usedDefaultDensity = false;
    List<double> weights = _grams ?? const [];
    if (weights.isEmpty && _volumeCm3 != null) {
      estimated = true;
      weights = [
        for (var i = 0; i < _volumeCm3!.length; i++)
          _volumeCm3![i] * _densityAt(i),
      ];
      usedDefaultDensity = _usedDefaultDensity(_volumeCm3!.length);
    } else if (weights.isEmpty && _lengthMm != null) {
      estimated = true;
      weights = [
        for (var i = 0; i < _lengthMm!.length; i++)
          _gramsFromMm(_lengthMm![i], _diameterAt(i), _densityAt(i)),
      ];
      usedDefaultDensity = _usedDefaultDensity(_lengthMm!.length);
    } else if (weights.isEmpty && _lengthM != null) {
      estimated = true;
      weights = [
        for (var i = 0; i < _lengthM!.length; i++)
          _gramsFromMm(_lengthM![i] * 1000, _diameterAt(i), _densityAt(i)),
      ];
      usedDefaultDensity = _usedDefaultDensity(_lengthM!.length);
    } else if (weights.isEmpty && _totalGrams != null) {
      weights = _totalGrams!;
    }

    final filaments = <GcodeFilament>[];
    for (var i = 0; i < weights.length; i++) {
      final grams = _roundGrams(weights[i]);
      if (grams <= 0) {
        continue;
      }
      filaments.add(
        GcodeFilament(
          grams: grams,
          material: i < _materials.length ? _materials[i] : '',
          colorHex: i < _colors.length ? _colors[i] : '',
        ),
      );
    }
    final notes = <String>[];
    if (estimated && filaments.isNotEmpty) {
      final l10n = activeGramnotaL10n;
      notes.add(
        usedDefaultDensity
            ? l10n.gcodeGramsEstimatedDefault
            : l10n.gcodeGramsEstimatedFromFile,
      );
    }
    return (filaments: filaments, notes: notes);
  }

  bool _usedDefaultDensity(int count) {
    for (var i = 0; i < count; i++) {
      final densityListed = i < (_densities?.length ?? 0) && _densities![i] > 0;
      final diameterListed =
          i < (_diameters?.length ?? 0) && _diameters![i] > 0;
      if (!densityListed || !diameterListed) {
        return true;
      }
    }
    return false;
  }

  double _densityAt(int index) {
    final values = _densities;
    if (values == null || values.isEmpty) {
      return _defaultDensity;
    }
    if (index < values.length && values[index] > 0) {
      return values[index];
    }
    if (values.length == 1 && values.first > 0) {
      return values.first;
    }
    return _defaultDensity;
  }

  double _diameterAt(int index) {
    final values = _diameters;
    if (values == null || values.isEmpty) {
      return _defaultDiameterMm;
    }
    if (index < values.length && values[index] > 0) {
      return values[index];
    }
    if (values.length == 1 && values.first > 0) {
      return values.first;
    }
    return _defaultDiameterMm;
  }
}

String _slicerLabel(String body) {
  final lower = body.toLowerCase();
  if (lower.contains('prusaslicer') || lower.contains('prusa slicer')) {
    return 'PrusaSlicer';
  }
  if (lower.contains('superslicer') || lower.contains('super slicer')) {
    return 'SuperSlicer';
  }
  if (lower.contains('orcaslicer') || lower.contains('orca slicer')) {
    return 'OrcaSlicer';
  }
  if (lower.contains('bambu')) {
    return 'Bambu Studio';
  }
  if (lower.contains('creality')) {
    return 'Creality Print';
  }
  if (lower.contains('cura')) {
    return 'Cura';
  }
  return '';
}

int? _parseDuration(String raw) {
  final text = raw.trim().toLowerCase();
  if (text.isEmpty) {
    return null;
  }
  if (RegExp(r'^\d+$').hasMatch(text)) {
    return int.parse(text);
  }
  final clock = RegExp(r'^(\d+):(\d{1,2}):(\d{1,2})$').firstMatch(text);
  if (clock != null) {
    return int.parse(clock.group(1)!) * 3600 +
        int.parse(clock.group(2)!) * 60 +
        int.parse(clock.group(3)!);
  }
  if (!RegExp(r'\d+\s*[dhms]').hasMatch(text)) {
    return null;
  }
  final days = _unitValue(text, 'd');
  final hours = _unitValue(text, 'h');
  final minutes = _unitValue(text, 'm');
  final seconds = _unitValue(text, 's');
  final total = days * 86400 + hours * 3600 + minutes * 60 + seconds;
  return total == 0 ? null : total;
}

int _unitValue(String text, String unit) {
  final match = RegExp('(\\d+)\\s*$unit(?![a-z])').firstMatch(text);
  if (match == null) {
    return 0;
  }
  return int.parse(match.group(1)!);
}

List<double> _parseNumberList(String raw) {
  var text = raw.trim();
  if (text.startsWith('[') && text.endsWith(']') && text.length >= 2) {
    text = text.substring(1, text.length - 1);
  }
  if (text.isEmpty) {
    return const [];
  }
  final parts = text.split(RegExp(r'[,;]'));
  final values = <double>[];
  for (final part in parts) {
    final value = _parseSlicerDouble(part);
    if (value != null) {
      values.add(value);
    }
  }
  return values;
}

double? _parseSlicerDouble(String raw) {
  var text = raw.trim().toLowerCase();
  text = text.replaceAll(RegExp(r'mm$'), '');
  text = text.replaceAll(RegExp(r'(g|m)$'), '');
  text = text.replaceAll(' ', '');
  if (text.isEmpty) {
    return null;
  }
  return double.tryParse(text);
}

List<String> _splitLabels(String value) {
  final text = value.trim();
  if (text.isEmpty) {
    return const [];
  }
  final separator = text.contains(';') ? ';' : ',';
  return [
    for (final part in text.split(separator))
      if (_cleanLabel(part).isNotEmpty) _cleanLabel(part),
  ];
}

String _cleanLabel(String part) {
  var text = part.trim();
  if (text.length >= 2 && text.startsWith('"') && text.endsWith('"')) {
    text = text.substring(1, text.length - 1).trim();
  }
  final lower = text.toLowerCase();
  if (lower.isEmpty || lower == 'nil' || lower == 'unknown') {
    return '';
  }
  return text;
}

void _assignLabels(List<String> target, List<String> values) {
  for (var i = 0; i < values.length; i++) {
    _setIndex(target, i, values[i]);
  }
}

void _setIndex(List<String> target, int index, String value) {
  while (target.length <= index) {
    target.add('');
  }
  if (value.isNotEmpty) {
    target[index] = value;
  }
}

String _normalizeColor(String raw) {
  var text = _cleanLabel(raw);
  if (text.startsWith('#')) {
    text = text.substring(1);
  }
  if (RegExp(r'^[0-9a-fA-F]{8}$').hasMatch(text)) {
    text = text.substring(0, 6);
  }
  if (RegExp(r'^[0-9a-fA-F]{6}$').hasMatch(text)) {
    return '#${text.toUpperCase()}';
  }
  return '';
}

double _gramsFromMm(double lengthMm, double diameterMm, double density) {
  if (lengthMm <= 0 || diameterMm <= 0 || density <= 0) {
    return 0;
  }
  final radiusCm = diameterMm / 20;
  final volume = (lengthMm / 10) * math.pi * radiusCm * radiusCm;
  return volume * density;
}

double _roundGrams(double grams) {
  if (grams.isNaN || grams.isInfinite || grams <= 0) {
    return 0;
  }
  return (grams * 1000).round() / 1000;
}
