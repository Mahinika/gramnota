    expect(weighted.printTimeSeconds, 3661);
    expect(weighted.filaments.map((item) => item.grams), [10.5, 3.2]);
    expect(weighted.filaments.map((item) => item.material), ['PLA', 'PETG']);
    expect(weighted.notes, isEmpty);

    final estimated = parseGcodeText('''
;TIME:60
;Filament used: 1m
;Generated with Cura_SteamEngine 5.6.0
''');
    expect(estimated.filaments.single.grams, 2.983);
    expect(estimated.notes.single, contains('1.75 mm and 1.24 g/cm³'));

    final fromFile = parseGcodeText('''
;TIME:60
;Filament used: 1m
;Filament diameter: 1.75
;Filament density: 1.24
;Generated with Cura_SteamEngine 5.4.0
''');
    expect(fromFile.filaments.single.grams, 2.983);
    expect(fromFile.notes.single, contains('diameter and density in the file'));
  });

