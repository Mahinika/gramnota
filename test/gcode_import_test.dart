class _SeededSlice extends PendingSlice {
  _SeededSlice(this.initial);

  final String? initial;

  @override
  String? build() => initial;
}

String _field(WidgetTester tester, String label) {
  final field = tester.widget<TextField>(find.widgetWithText(TextField, label));
  return field.controller?.text ?? '';
}

class _EdgeFile implements ByteSource {
  _EdgeFile({required this.length, required this.header, required this.footer});

  @override
  final int length;
  final Uint8List header;
  final Uint8List footer;
  var touchedGap = false;

  @override
  Future<Uint8List> read(int start, int end) async {
    final gapStart = gcodeHeadBytes;
    final gapEnd = length - gcodeTailBytes;
    if (start < gapEnd && end > gapStart) {
      touchedGap = true;
      throw StateError('Read $start..$end includes the skipped toolpath.');
    }
    final out = Uint8List(end - start);
    for (var index = start; index < end; index++) {
      final local = index - start;
      if (index < header.length) {
        out[local] = header[index];
      } else if (index >= length - footer.length) {
        out[local] = footer[index - (length - footer.length)];
      } else {
        out[local] = 0x0A;
      }
    }
    return out;
  }
}

class _ZipEntry {
  _ZipEntry(this.name, this.data, {this.deflate = false});

  final String name;
  final List<int> data;
  final bool deflate;
}

Uint8List _zip(List<_ZipEntry> entries) {
  final locals = BytesBuilder(copy: false);
  final central = BytesBuilder(copy: false);
  var offset = 0;
  for (final entry in entries) {
    final name = utf8.encode(entry.name);
    final stored = Uint8List.fromList(entry.data);
    final payload = entry.deflate
        ? Uint8List.fromList(ZLibCodec(raw: true).encode(stored))
        : stored;
    final local = BytesBuilder(copy: false)
      ..add(_le32(0x04034b50))
      ..add(_le16(20))
      ..add(_le16(0))
      ..add(_le16(entry.deflate ? 8 : 0))
      ..add(_le16(0))
      ..add(_le16(0))
      ..add(_le32(0))
      ..add(_le32(payload.length))
      ..add(_le32(stored.length))
      ..add(_le16(name.length))
      ..add(_le16(0))
      ..add(name)
      ..add(payload);
    final localBytes = local.toBytes();
    locals.add(localBytes);
    central
      ..add(_le32(0x02014b50))
      ..add(_le16(20))
      ..add(_le16(20))
      ..add(_le16(0))
      ..add(_le16(entry.deflate ? 8 : 0))
      ..add(_le16(0))
      ..add(_le16(0))
      ..add(_le32(0))
      ..add(_le32(payload.length))
      ..add(_le32(stored.length))
      ..add(_le16(name.length))
      ..add(_le16(0))
      ..add(_le16(0))
      ..add(_le16(0))
      ..add(_le16(0))
      ..add(_le32(0))
      ..add(_le32(offset))
      ..add(name);
    offset += localBytes.length;
  }
  final directory = central.toBytes();
  final end = BytesBuilder(copy: false)
    ..add(_le32(0x06054b50))
    ..add(_le16(0))
    ..add(_le16(0))
    ..add(_le16(entries.length))
    ..add(_le16(entries.length))
    ..add(_le32(directory.length))
    ..add(_le32(offset))
    ..add(_le16(0));
  return (BytesBuilder(copy: false)
        ..add(locals.toBytes())
        ..add(directory)
        ..add(end.toBytes()))
      .toBytes();
}

List<int> _le16(int value) => [value & 0xff, (value >> 8) & 0xff];

List<int> _le32(int value) => [
  value & 0xff,
  (value >> 8) & 0xff,
  (value >> 16) & 0xff,
  (value >> 24) & 0xff,
];
