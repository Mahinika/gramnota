void main() {
  test('reads PrusaSlicer, OrcaSlicer, and SuperSlicer comments', () {
    final prusa = parseGcodeText('''
; generated by PrusaSlicer 2.7.4+win64 on 2026-01-01 at 12:00:00 UTC
; filament used [mm] = 4000.00, 800.00
; filament used [g] = 12.50, 0, 2.25
; filament_type = PLA;PETG;ABS
; filament_colour = #FF8000;#112233;#ABCDEF
; estimated printing time (silent mode) = 3h 0m 0s
; estimated printing time (normal mode) = 1h 2m 3s
''');
    expect(prusa.slicer, 'PrusaSlicer');
    expect(prusa.printTimeSeconds, 3723);
    expect(prusa.filaments, hasLength(2));
    expect(prusa.filaments[0].grams, 12.5);
    expect(prusa.filaments[0].material, 'PLA');
    expect(prusa.filaments[0].colorHex, '#FF8000');
    expect(prusa.filaments[1].grams, 2.25);
    expect(prusa.filaments[1].material, 'ABS');
    expect(prusa.filaments[1].colorHex, '#ABCDEF');

    final orca = parseGcodeText('''
; generated by OrcaSlicer 2.2.0 on 2026-01-01 at 00:00:00 UTC
; filament used [g] = 2.98, 1.49
; filament_type = PLA;PETG
; filament_colour = #FFFFFF;#112233
; estimated printing time (normal mode) = 45m 10s
''');
    expect(orca.slicer, 'OrcaSlicer');
    expect(orca.printTimeSeconds, 45 * 60 + 10);
    expect(orca.filaments.map((item) => item.material), ['PLA', 'PETG']);

    final superSlicer = parseGcodeText('''
; generated by SuperSlicer 2.5.59 on 2026-01-01 at 00:00:00 UTC
; total filament used [g] = 4.5
; estimated printing time (normal mode) = 12m
''');
    expect(superSlicer.slicer, 'SuperSlicer');
    expect(superSlicer.printTimeSeconds, 12 * 60);
    expect(superSlicer.filaments.single.grams, 4.5);
  });

  test('prefers Bambu total time and per-extruder grams', () {
    final plate = parseGcodeText('''
; HEADER_BLOCK_START
; BambuStudio 01.09.01.00
; model printing time: 10m 0s; total estimated time: 12m 30s
; total filament used [g] = 8.50
; filament used [g] = 6.00, 2.50
; filament_type = PLA;PLA
; filament_colour = #FF0000;#00FF00
; HEADER_BLOCK_END
